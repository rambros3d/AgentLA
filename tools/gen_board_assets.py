#!/usr/bin/env python3
"""
AgentLA Board Asset & Header Generator (SSOT Pipeline)
Parses boards/<board_id>/board.json, validates schema, generates
firmware/src/generated/board_config.h, and stages web assets for lwIP fsdata.
"""

import argparse
import json
import os
import shutil
import sys
from pathlib import Path

REQUIRED_ROOT_KEYS = ["board_id", "name", "version", "assets", "mcu", "features", "zones"]
REQUIRED_ASSET_KEYS = ["logo", "pinout"]
REQUIRED_MCU_KEYS = ["chip", "cores", "sram_bytes", "flash_bytes"]


def validate_board_manifest(data: dict, board_dir: Path) -> None:
    for key in REQUIRED_ROOT_KEYS:
        if key not in data:
            raise ValueError(f"Missing required manifest key: '{key}'")

    assets = data.get("assets", {})
    for akey in REQUIRED_ASSET_KEYS:
        if akey not in assets:
            raise ValueError(f"Missing required asset key in assets: '{akey}'")
        asset_file = board_dir / assets[akey]
        if not asset_file.exists():
            raise FileNotFoundError(f"Declared asset file not found: {asset_file}")

    mcu = data.get("mcu", {})
    for mkey in REQUIRED_MCU_KEYS:
        if mkey not in mcu:
            raise ValueError(f"Missing required mcu key: '{mkey}'")


def generate_header(data: dict, output_header: Path) -> None:
    board_id = data["board_id"]
    name = data["name"]
    version = data["version"]
    mcu = data["mcu"]
    features = data.get("features", {})
    zones = data.get("zones", {})

    has_can = 1 if features.get("has_hardware_can") else 0
    has_rs485 = 1 if features.get("has_hardware_rs485") else 0
    target_curr_sense = 1 if data.get("power_architecture", {}).get("target_power", {}).get("current_sense_ic") else 0

    header_lines = [
        "/* Auto-generated by tools/gen_board_assets.py from board.json */",
        "/* DO NOT EDIT MANUALLY - EDIT boards/<board_id>/board.json INSTEAD */",
        "#ifndef __AGENTLA_GENERATED_BOARD_CONFIG_H__",
        "#define __AGENTLA_GENERATED_BOARD_CONFIG_H__",
        "",
        f'#define AGENTLA_BOARD_ID           "{board_id}"',
        f'#define AGENTLA_BOARD_NAME         "{name}"',
        f'#define AGENTLA_BOARD_VERSION      "{version}"',
        "",
        f'#define BOARD_MCU_CHIP             "{mcu.get("chip", "RP2350")}"',
        f'#define BOARD_MCU_CORES            "{mcu.get("cores", "Dual Cortex-M33")}"',
        f'#define BOARD_MCU_SRAM_BYTES       ({mcu.get("sram_bytes", 524288)}UL)',
        f'#define BOARD_MCU_FLASH_BYTES      ({mcu.get("flash_bytes", 4194304)}UL)',
        "",
        f"#define BOARD_HAS_CAN              {has_can}",
        f"#define BOARD_HAS_RS485            {has_rs485}",
        f"#define BOARD_TARGET_CURRENT_SENSE {target_curr_sense}",
        "",
    ]

    # Network configuration (Defaults: 10.10.10.10 / agentla.local, overridable by board.json)
    network = data.get("network", {})
    ip_str = network.get("ip", "10.10.10.10")
    domain_str = network.get("domain", "agentla.local")
    netmask_str = network.get("netmask", "255.255.255.0")
    gateway_str = network.get("gateway", "0.0.0.0")

    try:
        ip_parts = [int(p) for p in ip_str.split(".")]
        if len(ip_parts) != 4:
            raise ValueError()
    except Exception:
        ip_parts = [10, 10, 10, 10]
        ip_str = "10.10.10.10"

    try:
        mask_parts = [int(p) for p in netmask_str.split(".")]
        if len(mask_parts) != 4:
            raise ValueError()
    except Exception:
        mask_parts = [255, 255, 255, 0]

    try:
        gw_parts = [int(p) for p in gateway_str.split(".")]
        if len(gw_parts) != 4:
            raise ValueError()
    except Exception:
        gw_parts = [0, 0, 0, 0]

    header_lines.append("/* Network Configuration (USB RNDIS / CDC-ECM) */")
    header_lines.append(f"#define BOARD_NET_IP_A             {ip_parts[0]}")
    header_lines.append(f"#define BOARD_NET_IP_B             {ip_parts[1]}")
    header_lines.append(f"#define BOARD_NET_IP_C             {ip_parts[2]}")
    header_lines.append(f"#define BOARD_NET_IP_D             {ip_parts[3]}")
    header_lines.append(f'#define BOARD_NET_IP_STR           "{ip_str}"')
    header_lines.append(f"#define BOARD_NET_MASK_A           {mask_parts[0]}")
    header_lines.append(f"#define BOARD_NET_MASK_B           {mask_parts[1]}")
    header_lines.append(f"#define BOARD_NET_MASK_C           {mask_parts[2]}")
    header_lines.append(f"#define BOARD_NET_MASK_D           {mask_parts[3]}")
    header_lines.append(f"#define BOARD_NET_GW_A             {gw_parts[0]}")
    header_lines.append(f"#define BOARD_NET_GW_B             {gw_parts[1]}")
    header_lines.append(f"#define BOARD_NET_GW_C             {gw_parts[2]}")
    header_lines.append(f"#define BOARD_NET_GW_D             {gw_parts[3]}")
    header_lines.append(f'#define BOARD_NET_DOMAIN           "{domain_str}"')
    header_lines.append("")

    # Pin defines from zones if available
    pin_defines = {}
    for zone_id, zone in zones.items():
        pins = zone.get("pins", {})
        for pin_name, pin_num in pins.items():
            def_name = f"PIN_{zone_id.upper()}_{pin_name.upper()}"
            if isinstance(pin_num, int):
                pin_defines[def_name] = pin_num

    if pin_defines:
        header_lines.append("/* Hardware Zone Specific Pin Allocations */")
        for def_name, pin_num in sorted(pin_defines.items()):
            header_lines.append(f"#define {def_name:<30} {pin_num}")
        header_lines.append("")

    header_lines.append("#endif /* __AGENTLA_GENERATED_BOARD_CONFIG_H__ */\n")

    output_header.parent.mkdir(parents=True, exist_ok=True)
    output_header.write_text("\n".join(header_lines), encoding="utf-8")
    print(f"[gen_board_assets] Generated C header: {output_header}")


def stage_web_assets(data: dict, board_dir: Path, output_web_dir: Path, base_html_dir: Path = None) -> None:
    output_web_dir.mkdir(parents=True, exist_ok=True)

    if base_html_dir and base_html_dir.is_dir():
        for src_file in base_html_dir.glob("*"):
            if src_file.is_file() and src_file.name not in ["board.json", "logo.svg", "pinout.svg"]:
                dst_file = output_web_dir / src_file.name
                shutil.copyfile(src_file, dst_file)
                print(f"[gen_board_assets] Staged base web file: {src_file.name}")

    # Copy master favicon from webui if not already copied
    master_favicon = (Path(__file__).parent.parent / "webui" / "favicon.svg").resolve()
    if master_favicon.is_file() and not (output_web_dir / "favicon.svg").exists():
        shutil.copyfile(master_favicon, output_web_dir / "favicon.svg")
        print(f"[gen_board_assets] Staged master favicon: {master_favicon} -> {output_web_dir / 'favicon.svg'}")

    # Minify board.json
    minified_json = json.dumps(data, separators=(",", ":"))
    dest_json = output_web_dir / "board.json"
    dest_json.write_text(minified_json, encoding="utf-8")
    print(f"[gen_board_assets] Staged minified manifest: {dest_json}")

    # Copy vector assets
    assets = data.get("assets", {})
    for akey, afilename in assets.items():
        src = board_dir / afilename
        dst = output_web_dir / afilename
        shutil.copyfile(src, dst)
        print(f"[gen_board_assets] Staged asset: {src} -> {dst}")


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate AgentLA board assets and C headers")
    parser.add_argument("--board", default="pico2", help="Board identifier (pico2, bakuprobe)")
    parser.add_argument("--boards-dir", default="boards", help="Directory containing board definitions")
    parser.add_argument("--base-html-dir", default=None, help="Directory containing base HTML/CSS/JS files to stage")
    parser.add_argument("--output-header", default="firmware/src/generated/board_config.h", help="Output C header path")
    parser.add_argument("--output-web-dir", default="webui/generated", help="Staging directory for web assets")
    args = parser.parse_args()

    boards_dir = Path(args.boards_dir).resolve()
    board_dir = boards_dir / args.board
    manifest_path = board_dir / "board.json"

    if not manifest_path.exists():
        print(f"[gen_board_assets] ERROR: Board manifest not found: {manifest_path}", file=sys.stderr)
        return 1

    try:
        manifest_data = json.loads(manifest_path.read_text(encoding="utf-8"))
        validate_board_manifest(manifest_data, board_dir)
    except Exception as e:
        print(f"[gen_board_assets] ERROR validating manifest {manifest_path}: {e}", file=sys.stderr)
        return 1

    output_header = Path(args.output_header).resolve()
    output_web_dir = Path(args.output_web_dir).resolve()
    base_html_dir = Path(args.base_html_dir).resolve() if args.base_html_dir else None

    # Compile themes if themes directory exists
    repo_root = Path(__file__).resolve().parent.parent
    themes_dir = repo_root / "themes"
    if themes_dir.is_dir() and base_html_dir:
        compile_script = Path(__file__).resolve().parent / "compile_themes.py"
        if compile_script.exists():
            try:
                import importlib.util
                spec = importlib.util.spec_from_file_location("compile_themes", str(compile_script))
                mod = importlib.util.module_from_spec(spec)
                spec.loader.exec_module(mod)
                mod.compile_themes(themes_dir, base_html_dir / "themes.css", base_html_dir / "themes.json")
            except Exception as e:
                print(f"[gen_board_assets] Warning: Theme compilation error: {e}", file=sys.stderr)

    generate_header(manifest_data, output_header)
    stage_web_assets(manifest_data, board_dir, output_web_dir, base_html_dir=base_html_dir)

    print(f"[gen_board_assets] Success: board '{args.board}' configured cleanly.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
